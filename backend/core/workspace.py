"""Account-scoped workspace with SQLite or PostgreSQL transactions."""
import hashlib
import hmac
import json
import secrets
import sqlite3
import time
from contextlib import contextmanager
from pathlib import Path

from fastapi import HTTPException, Request
from core.config import settings


class _PostgresConnection:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, statement, params=None):
        # Workspace statements are fixed SQL with SQLite-style parameter markers.
        # Values always go separately through the database driver.
        return self.connection.execute(statement.replace('?', '%s'), params)


class Workspace:
    def __init__(self, path, *, database_url=''):
        self.path = str(path)
        self._database_url = database_url.strip()
        self.backend = 'postgresql' if self._database_url else 'sqlite'
        if self.backend == 'postgresql':
            event_id = 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
        else:
            event_id = 'INTEGER PRIMARY KEY'
            Path(self.path).parent.mkdir(parents=True, exist_ok=True)
            with self.connect() as db:
                db.execute('PRAGMA journal_mode=WAL')

        with self.connect(lock='workspace-schema-v1') as db:
            schema = f'''
                CREATE TABLE IF NOT EXISTS users(id TEXT PRIMARY KEY, name TEXT UNIQUE, password TEXT);
                CREATE TABLE IF NOT EXISTS google_identities(
                    subject TEXT PRIMARY KEY, owner TEXT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE);
                CREATE TABLE IF NOT EXISTS tokens(hash TEXT PRIMARY KEY, owner TEXT, expires DOUBLE PRECISION);
                CREATE TABLE IF NOT EXISTS documents(
                    id TEXT PRIMARY KEY, owner TEXT NOT NULL, kind TEXT NOT NULL,
                    version INTEGER NOT NULL, body TEXT NOT NULL, updated DOUBLE PRECISION NOT NULL);
                CREATE INDEX IF NOT EXISTS docs_owner ON documents(owner,kind,updated);
                CREATE TABLE IF NOT EXISTS revisions(
                    id TEXT, version INTEGER, body TEXT, created DOUBLE PRECISION, PRIMARY KEY(id,version));
                CREATE TABLE IF NOT EXISTS submissions(
                    reference TEXT PRIMARY KEY, owner TEXT, draft TEXT, version INTEGER,
                    state TEXT, payload TEXT, result TEXT, updated DOUBLE PRECISION,
                    UNIQUE(draft,version));
                CREATE TABLE IF NOT EXISTS events(
                    id {event_id}, owner TEXT, name TEXT, entity TEXT, created DOUBLE PRECISION);
                CREATE TABLE IF NOT EXISTS chat_leases(id TEXT PRIMARY KEY, token TEXT, expires DOUBLE PRECISION);
                CREATE TABLE IF NOT EXISTS callback_receipts(id TEXT PRIMARY KEY, updated DOUBLE PRECISION, done INTEGER);
            '''
            for statement in schema.split(';'):
                if statement.strip():
                    db.execute(statement)
            if self.backend == 'postgresql':
                db.execute("""
                    CREATE TABLE IF NOT EXISTS catalog_snapshots(
                        source TEXT NOT NULL, format_version INTEGER NOT NULL,
                        fetched_at BIGINT NOT NULL, payload BYTEA NOT NULL,
                        PRIMARY KEY (source, format_version)
                    )
                """)

    @contextmanager
    def connect(self, *, lock=None):
        if self.backend == 'postgresql':
            import psycopg
            from psycopg.rows import dict_row

            try:
                connection = psycopg.connect(self._database_url, row_factory=dict_row, connect_timeout=10,
                                             prepare_threshold=None)
            except psycopg.Error:
                raise RuntimeError('Could not connect to the configured workspace database. '
                                   'Check WORKSPACE_DATABASE_URL, network access, and PostgreSQL credentials.') from None
            with connection:
                if lock:
                    connection.execute('SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))', (lock,))
                yield _PostgresConnection(connection)
            return

        db = sqlite3.connect(self.path, timeout=15)
        db.row_factory = sqlite3.Row
        try:
            if lock:
                db.execute('BEGIN IMMEDIATE')
            yield db
            db.commit()
        except BaseException:
            db.rollback()
            raise
        finally:
            db.close()

    def register(self, name, password):
        name = name.strip().casefold()
        if not 3 <= len(name) <= 80 or not 10 <= len(password) <= 256:
            raise HTTPException(422, 'Tên tài khoản 3–80 ký tự, mật khẩu 10–256 ký tự.')
        salt = secrets.token_hex(16)
        digest = hashlib.scrypt(password.encode(), salt=bytes.fromhex(salt), n=16384, r=8, p=1).hex()
        owner = secrets.token_hex(16)
        with self.connect() as db:
            created = db.execute('INSERT INTO users VALUES(?,?,?) ON CONFLICT DO NOTHING',
                                 (owner, name, salt + ':' + digest))
            if created.rowcount != 1:
                raise HTTPException(409, 'Tên tài khoản đã tồn tại.')
        return owner

    def login(self, name, password):
        with self.connect() as db:
            row = db.execute('SELECT * FROM users WHERE name=?', (name.strip().casefold(),)).fetchone()
        # Use the same work for unknown names and accounts that only use Google.
        stored = row['password'] if row else ''
        salt, expected = (stored or '00' * 16 + ':' + '00' * 64).split(':')
        actual = hashlib.scrypt(password.encode(), salt=bytes.fromhex(salt), n=16384, r=8, p=1).hex()
        if not stored or not hmac.compare_digest(actual, expected):
            raise HTTPException(401, 'Tài khoản hoặc mật khẩu không đúng.')
        return row['id']

    def login_google(self, subject: str, email: str) -> str:
        email = email.strip().casefold()
        with self.connect(lock=f'google-login:{subject}') as db:
            identity = db.execute('SELECT owner FROM google_identities WHERE subject=?', (subject,)).fetchone()
            if identity:
                return identity['owner']

            owner = secrets.token_hex(16)
            # A password account can use any name, so an email match does not prove ownership.
            for name in (email, f'{email} (google)', f'{email} (google {owner})'):
                created = db.execute('INSERT INTO users VALUES(?,?,?) ON CONFLICT DO NOTHING', (owner, name, ''))
                if created.rowcount == 1:
                    db.execute('INSERT INTO google_identities VALUES(?,?)', (subject, owner))
                    return owner
        raise HTTPException(409, 'Chưa tạo được tài khoản Google. Vui lòng thử lại.')

    def token(self, owner):
        token = secrets.token_urlsafe(32)
        with self.connect() as db:
            db.execute('DELETE FROM tokens WHERE expires<?', (time.time(),))
            db.execute('INSERT INTO tokens VALUES(?,?,?)',
                       (hashlib.sha256(token.encode()).hexdigest(), owner, time.time() + 86400 * 7))
        return token

    def owner(self, token):
        with self.connect() as db:
            row = db.execute('SELECT owner FROM tokens WHERE hash=? AND expires>?',
                             (hashlib.sha256(token.encode()).hexdigest(), time.time())).fetchone()
        if not row:
            raise HTTPException(401, 'Vui lòng đăng nhập.')
        return row['owner']

    def create(self, owner, kind, body):
        ident = secrets.token_hex(16)
        with self.connect() as db:
            db.execute('INSERT INTO documents VALUES(?,?,?,?,?,?)',
                       (ident, owner, kind, 1, json.dumps(body, ensure_ascii=False), time.time()))
            db.execute('INSERT INTO revisions VALUES(?,?,?,?)',
                       (ident, 1, json.dumps(body, ensure_ascii=False), time.time()))
        return self.get(owner, ident, kind)

    @staticmethod
    def decode(row):
        return dict(id=row['id'], version=row['version'], updated_at=row['updated'], **json.loads(row['body']))

    def get(self, owner, ident, kind):
        with self.connect() as db:
            row = db.execute('SELECT * FROM documents WHERE id=? AND owner=? AND kind=?',
                             (ident, owner, kind)).fetchone()
        if not row:
            raise HTTPException(404, 'Không tìm thấy dữ liệu trong tài khoản này.')
        return self.decode(row)

    def list(self, owner, kind):
        with self.connect() as db:
            return [self.decode(r) for r in db.execute(
                'SELECT * FROM documents WHERE owner=? AND kind=? ORDER BY updated DESC', (owner, kind))]

    def asset_for_share_token(self, token):
        expression = "CAST(body AS jsonb)->>'share_token'" if self.backend == 'postgresql' else "json_extract(body,'$.share_token')"
        with self.connect() as db:
            row = db.execute(f"SELECT * FROM documents WHERE kind='asset' AND ({expression})=?", (token,)).fetchone()
        if not row:
            raise HTTPException(404)
        return self.decode(row)

    def update(self, owner, ident, kind, version, body):
        with self.connect(lock=f'{kind}:{ident}') as db:
            # Submitted/uncertain drafts are frozen until reconciled.
            if kind == 'draft' and db.execute(
                "SELECT 1 FROM submissions WHERE draft=? AND state IN ('sending','verifying','created')", (ident,)
            ).fetchone():
                raise HTTPException(409, 'Đơn đang gửi/đang xác minh hoặc đã tạo. Không thể sửa; hãy kiểm tra đơn hàng.')
            result = db.execute('UPDATE documents SET version=version+1, body=?, updated=? '
                                'WHERE id=? AND owner=? AND kind=? AND version=?',
                                (json.dumps(body, ensure_ascii=False), time.time(), ident, owner, kind, version))
            if result.rowcount != 1:
                raise HTTPException(409, 'Dữ liệu đã thay đổi ở tab khác. Tải lại trước khi sửa.')
            db.execute('INSERT INTO revisions VALUES(?,?,?,?)',
                       (ident, version + 1, json.dumps(body, ensure_ascii=False), time.time()))
        return self.get(owner, ident, kind)

    def event(self, owner, name, entity=''):
        with self.connect() as db:
            db.execute('INSERT INTO events(owner,name,entity,created) VALUES(?,?,?,?)',
                       (owner, name, entity, time.time()))


workspace = Workspace(settings.WORKSPACE_DB_PATH, database_url=settings.WORKSPACE_DATABASE_URL)


def current_owner(request: Request):
    return workspace.owner(request.cookies.get('bp_session', ''))
